  CROPS.find(c => c.id === id);

export const getCropsByCategory = (category: Crop['category']): Crop[] =>
  CROPS.filter(c => c.category === category);

export const getCropsByIds = (ids: string[]): Crop[] =>
  ids.map(id => getCropById(id)).filter(Boolean) as Crop[];
